/**
 * The fonts a spine's title and author can be set in. Each is self-hosted
 * (src/styles/fonts.css) and only downloads when a spine on screen uses it.
 * The ids are stored in the manifest, so never rename one.
 */

export interface SpineFont {
  id: string
  /** Shown in the font picker. */
  label: string
  /** The @font-face family name. */
  family: string
  /** CSS font-family value, with fallbacks. */
  stack: string
  weight: number
}

const font = (id: string, label: string, weight = 400, fallback = '"Times New Roman", Georgia, serif'): SpineFont => ({
  id,
  label,
  family: label,
  // "<name> fallback" is a metric-matched local face generated by fontaine at build time.
  stack: `"${label}", "${label} fallback", ${fallback}`,
  weight,
})

export const DEFAULT_FONT_ID = 'instrument-serif'

export const SPINE_FONTS: readonly SpineFont[] = [
  font(DEFAULT_FONT_ID, 'Instrument Serif'),
  font('eb-garamond', 'EB Garamond'), // free stand-in for Adobe Garamond
  font('cardo', 'Cardo'), // for Bembo
  font('pagella', 'TeX Gyre Pagella', 400, 'Palatino, "Palatino Linotype", "Book Antiqua", Georgia, serif'), // for Palatino
  font('cormorant-garamond', 'Cormorant Garamond', 500), // for Sabon; 400 is too thin at spine sizes
  font('crimson-pro', 'Crimson Pro'), // for Minion
]

/** The font for a stored id; missing or unknown ids get Instrument Serif. */
export function fontFor(id?: string | null): SpineFont {
  return SPINE_FONTS.find((f) => f.id === id) ?? SPINE_FONTS[0]
}

/** A CSS `font` shorthand for measuring or loading `f` at `size` px. */
export const fontShorthand = (f: SpineFont, size: number) => `${f.weight} ${size}px ${f.stack}`

/**
 * Starts loading `f` if it isn't loaded yet. Resolves once it's ready, or
 * returns null when there's nothing to wait for (already loaded, or no
 * FontFace API).
 */
export function loadFont(f: SpineFont, fonts: FontFaceSet | undefined = globalThis.document?.fonts): Promise<void> | null {
  if (!fonts?.check || !fonts.load) return null
  const shorthand = fontShorthand(f, 16)
  if (fonts.check(shorthand)) return null
  return fonts.load(shorthand).then(() => undefined, () => undefined)
}
